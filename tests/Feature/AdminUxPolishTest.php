it('aligns countOpen with the sum of tab counts after moving MdSignup out', function () {
    // Two generic enquiries + one MD signup. countOpen excludes MdSignup
    // because match-director requests live on their own Inbox tab.
    Enquiry::create([
        'type' => EnquiryType::General,
        'name' => 'A',
        'email' => 'a-'.uniqid().'@example.com',
        'subject' => 'x',
        'body' => 'x',
        'status' => EnquiryStatus::New,
    ]);
    Enquiry::create([
        'type' => EnquiryType::General,
        'name' => 'B',
        'email' => 'b-'.uniqid().'@example.com',
        'subject' => 'x',
        'body' => 'x',
        'status' => EnquiryStatus::New,
    ]);
    Enquiry::create([
        'type' => EnquiryType::MdSignup,
        'name' => 'C',
        'email' => 'c-'.uniqid().'@example.com',
        'subject' => 'x',
        'body' => 'x',
        'status' => EnquiryStatus::New,
    ]);

    // 2 enquiries on the Enquiries tab + 1 director request on its own
    // tab = 3 total. If MdSignup was still counted on the Enquiries tab
    // too, this would be 4.
    expect(Inbox::countOpen())->toBe(3);
});

