// --- Inbox always-show counts ------------------------------------------

it('always renders Inbox tab count badges, including zero', function () {
    $staff = User::factory()->staff()->create();

    // No pending anything — tab counts should all be 0 but still visible.
    $html = $this->actingAs($staff)
        ->get(Inbox::getUrl())
        ->assertOk()
        ->getContent();

    // The Inbox blade now renders a secondary 0 badge for every tab;
    // if the count conditional came back we would see no badges at all
